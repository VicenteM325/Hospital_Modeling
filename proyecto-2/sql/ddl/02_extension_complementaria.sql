-- Migracion complementaria - datos que piden los objetivos 3, 4, 8 y 12
-- El modelo del Proyecto 1 no guardaba turnos laborados, turnos de espera ni metodo de pago.
-- Migracion ADITIVA: solo agrega una tabla, una funcion y dos columnas con valores por defecto.
-- Ejecutar como usr_admin_bd, despues de 01_extension_personal.sql.

SET ROLE rol_administrador;
BEGIN;

-- ---------------------------------------------------------------------------------------------
-- 1. Definicion unica de "turno" segun la hora (la usan turno_laboral y las consultas del objetivo 12)
-- ---------------------------------------------------------------------------------------------
CREATE FUNCTION turno_de_hora(p_fecha_hora TIMESTAMP) RETURNS VARCHAR(10) LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN EXTRACT(HOUR FROM p_fecha_hora) >= 6  AND EXTRACT(HOUR FROM p_fecha_hora) < 14 THEN 'Matutino'
        WHEN EXTRACT(HOUR FROM p_fecha_hora) >= 14 AND EXTRACT(HOUR FROM p_fecha_hora) < 22 THEN 'Vespertino'
        ELSE 'Nocturno'
    END
$$;
COMMENT ON FUNCTION turno_de_hora(TIMESTAMP) IS 'Turno de una hora: Matutino 06-14, Vespertino 14-22, Nocturno 22-06';

-- ---------------------------------------------------------------------------------------------
-- 2. Turnos laborados por los medicos (objetivo 3: horas y turnos laborados en Emergencias)
-- ---------------------------------------------------------------------------------------------
CREATE TABLE turno_laboral (
    id_turno_laboral    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medico           INTEGER NOT NULL
        CONSTRAINT fk_turno_medico REFERENCES medico(id_medico)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    id_unidad_hospital  INTEGER NOT NULL
        CONSTRAINT fk_turno_unidad REFERENCES unidad_hospital(id_unidad_hospital)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    fecha_hora_inicio   TIMESTAMP NOT NULL,
    fecha_hora_fin      TIMESTAMP NOT NULL
        CONSTRAINT chk_turno_fin_posterior CHECK (fecha_hora_fin > fecha_hora_inicio), -- valida que el turno termine despues de empezar
    turno               VARCHAR(10) GENERATED ALWAYS AS (turno_de_hora(fecha_hora_inicio)) STORED
        CONSTRAINT chk_turno_nombre CHECK (turno IN ('Matutino', 'Vespertino', 'Nocturno')), -- valida el turno, derivado de la hora de inicio
    CONSTRAINT chk_turno_duracion CHECK (fecha_hora_fin - fecha_hora_inicio <= INTERVAL '24 hours'), -- valida que un turno no dure mas de un dia
    CONSTRAINT uq_turno_medico_inicio UNIQUE (id_medico, fecha_hora_inicio)
);
COMMENT ON TABLE turno_laboral IS 'Turno trabajado por un medico en una unidad de su hospital; base de las horas y turnos laborados';
CREATE INDEX idx_turno_unidad ON turno_laboral (id_unidad_hospital);

-- Reglas entre filas que un CHECK no puede expresar: la unidad es del hospital del medico y los turnos no se traslapan
CREATE FUNCTION fn_turno_validar() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (SELECT id_hospital FROM medico WHERE id_medico = NEW.id_medico)
       IS DISTINCT FROM (SELECT id_hospital FROM unidad_hospital WHERE id_unidad_hospital = NEW.id_unidad_hospital) THEN
        RAISE EXCEPTION 'La unidad % no pertenece al hospital del medico %', NEW.id_unidad_hospital, NEW.id_medico;
    END IF;
    IF EXISTS (
        SELECT 1 FROM turno_laboral t
        WHERE t.id_medico = NEW.id_medico
          AND t.id_turno_laboral IS DISTINCT FROM NEW.id_turno_laboral
          AND t.fecha_hora_inicio < NEW.fecha_hora_fin AND NEW.fecha_hora_inicio < t.fecha_hora_fin
    ) THEN
        RAISE EXCEPTION 'El turno se traslapa con otro turno del medico %', NEW.id_medico;
    END IF;
    RETURN NEW;
END
$$;
COMMENT ON FUNCTION fn_turno_validar() IS 'Valida que la unidad sea del hospital del medico y que sus turnos no se traslapen';

CREATE TRIGGER trg_turno_validar BEFORE INSERT OR UPDATE ON turno_laboral
    FOR EACH ROW EXECUTE FUNCTION fn_turno_validar();

-- ---------------------------------------------------------------------------------------------
-- 3. Turno de espera en el ingreso (objetivo 4: eficiencia de Emergencias)
-- ---------------------------------------------------------------------------------------------
ALTER TABLE ingreso
    ADD COLUMN turno_espera INTEGER
        CONSTRAINT chk_ingreso_turno_espera CHECK (turno_espera IS NULL OR turno_espera >= 0); -- valida que los turnos de espera no sean negativos
COMMENT ON COLUMN ingreso.turno_espera IS 'Turnos de la fila que espero el paciente antes de ser atendido (0 = atendido de inmediato; NULL = no registrado)';

-- ---------------------------------------------------------------------------------------------
-- 4. Metodo de pago de cada cuota (objetivo 8)
-- ---------------------------------------------------------------------------------------------
ALTER TABLE cuota
    ADD COLUMN metodo_pago VARCHAR(20) NOT NULL DEFAULT 'Efectivo'
        CONSTRAINT chk_cuota_metodo_pago CHECK (metodo_pago IN ('Efectivo', 'Tarjeta de credito', 'Tarjeta de debito')); -- valida el metodo con que se paga la cuota
COMMENT ON COLUMN cuota.metodo_pago IS 'Metodo con el que se pago la cuota; las cuotas del Proyecto 1 quedan como Efectivo';

COMMIT;
