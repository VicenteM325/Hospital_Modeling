COMMENT ON COLUMN medico.id_personal IS 'Enlace 1:1 con el supertipo personal';
COMMENT ON COLUMN medico.cargo IS 'Nivel jerarquico: Director Medico, Jefe de Servicio o Medico';
COMMENT ON COLUMN medico.id_supervisor IS 'Jefe directo (relacion recursiva); NULL solo para el director medico o personal aun sin asignar';
COMMENT ON COLUMN medico.salario IS 'Salario mensual; dato sensible auditado (objetivo 20)';
COMMENT ON COLUMN medico.nivel_acceso IS 'Nivel de acceso al sistema; dato sensible auditado (objetivo 20)';
COMMENT ON COLUMN enfermero.id_personal IS 'Enlace 1:1 con el supertipo personal';
COMMENT ON COLUMN enfermero.numero_colegiado IS 'Numero de colegiado profesional, si lo tiene';
COMMENT ON COLUMN personal_encargado.id_personal IS 'Enlace 1:1 con el supertipo personal';

COMMIT;
