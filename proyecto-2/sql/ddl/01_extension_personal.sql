-- DDL P2-01: Extension del modelo (Bloque B) - supertipo PERSONAL y jerarquia de medicos
-- Migracion ADITIVA sobre el Proyecto 1: no se elimina ni se renombra ninguna tabla ni columna existente.
-- Ejecutar como usr_admin_bd, despues de sql/dcl/01_propiedad_y_privilegios_extension.sql.
--
-- Estrategia supertipo/subtipo = TABLA POR TIPO:
--   PERSONAL (datos comunes) + MEDICO / ENFERMERO / PERSONAL_ENCARGADO (datos propios de cada
--   funcion), enlazados 1:1 por id_personal.

SET ROLE rol_administrador;
BEGIN;

-- ---------------------------------------------------------------------------------------------
-- 1. SUPERTIPO: datos que comparten medicos, enfermeros y personal encargado
-- ---------------------------------------------------------------------------------------------
CREATE TABLE personal (
    id_personal         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_personal       VARCHAR(10) NOT NULL
        CONSTRAINT chk_personal_tipo CHECK (tipo_personal IN ('Medico', 'Enfermero', 'Encargado')), -- valida el discriminador del supertipo (subtipos excluyentes)
    nombre              VARCHAR(150) NOT NULL
        CONSTRAINT chk_personal_nombre CHECK (length(btrim(nombre)) > 0), -- valida que el nombre no este vacio
    dpi                 VARCHAR(13) NOT NULL UNIQUE
        CONSTRAINT chk_personal_dpi CHECK (dpi ~ '^[0-9]{13}$'), -- valida el formato del DPI: 13 digitos
    fecha_contratacion  DATE NOT NULL
        CONSTRAINT chk_personal_fecha_contratacion CHECK (fecha_contratacion <= CURRENT_DATE), -- valida que no se registre una contratacion futura
    telefono            VARCHAR(20)
        CONSTRAINT chk_personal_telefono CHECK (telefono IS NULL OR telefono ~ '^[0-9]{8}$'), -- valida telefono de 8 digitos si se registra
    direccion           VARCHAR(200),
    CONSTRAINT uq_personal_id_tipo UNIQUE (id_personal, tipo_personal) -- permite la FK compuesta que fuerza el tipo en cada subtipo
);
COMMENT ON TABLE personal IS 'Supertipo del personal del hospital: datos comunes de medicos, enfermeros y personal encargado';

-- ---------------------------------------------------------------------------------------------
-- 2. SUBTIPO MEDICO: se enlaza con PERSONAL y se agrega la cadena de mando
-- ---------------------------------------------------------------------------------------------
ALTER TABLE medico
    ADD COLUMN id_personal    INTEGER,
    ADD COLUMN tipo_personal  VARCHAR(10) NOT NULL DEFAULT 'Medico'
        CONSTRAINT chk_medico_tipo_personal CHECK (tipo_personal = 'Medico'), -- valida que el subtipo solo enlace con personal de tipo Medico
    ADD COLUMN cargo          VARCHAR(20) NOT NULL DEFAULT 'Medico'
        CONSTRAINT chk_medico_cargo CHECK (cargo IN ('Director Medico', 'Jefe de Servicio', 'Medico')), -- valida el nivel jerarquico del medico
    ADD COLUMN id_supervisor  INTEGER,
    ADD COLUMN salario        NUMERIC(10, 2)
        CONSTRAINT chk_medico_salario CHECK (salario IS NULL OR salario >= 0), -- valida que el salario no sea negativo
    ADD COLUMN nivel_acceso   VARCHAR(15) NOT NULL DEFAULT 'Basico'
        CONSTRAINT chk_medico_nivel_acceso CHECK (nivel_acceso IN ('Basico', 'Intermedio', 'Avanzado', 'Administrador')); -- valida el nivel de acceso al sistema

-- Migracion de los medicos del Proyecto 1 hacia el supertipo.
-- El Proyecto 1 no registraba la contratacion: se asigna la fecha de corte 2026-01-01 y el DML la corrige con datos ficticios.
INSERT INTO personal (tipo_personal, nombre, dpi, telefono, fecha_contratacion)
SELECT 'Medico', nombre, dpi, telefono, DATE '2026-01-01' FROM medico ORDER BY id_medico;

UPDATE medico m SET id_personal = p.id_personal
FROM personal p WHERE p.tipo_personal = 'Medico' AND p.dpi = m.dpi;

-- Jerarquia inicial: el medico de menor id de cada hospital es su director y los demas le reportan.
UPDATE medico m SET cargo = 'Director Medico'
WHERE m.id_medico = (SELECT MIN(d.id_medico) FROM medico d WHERE d.id_hospital = m.id_hospital);

UPDATE medico m SET id_supervisor = d.id_medico
FROM medico d
WHERE d.cargo = 'Director Medico' AND d.id_hospital = m.id_hospital AND m.cargo <> 'Director Medico';

ALTER TABLE medico
    ALTER COLUMN id_personal SET NOT NULL,
    ADD CONSTRAINT uq_medico_id_personal UNIQUE (id_personal),
    ADD CONSTRAINT fk_medico_personal FOREIGN KEY (id_personal, tipo_personal)
        REFERENCES personal (id_personal, tipo_personal) ON DELETE RESTRICT ON UPDATE CASCADE,
    ADD CONSTRAINT uq_medico_hospital_medico UNIQUE (id_hospital, id_medico), -- permite la FK compuesta que obliga a que supervisor y subordinado sean del mismo hospital
    ADD CONSTRAINT fk_medico_supervisor FOREIGN KEY (id_hospital, id_supervisor)
        REFERENCES medico (id_hospital, id_medico) ON DELETE RESTRICT ON UPDATE RESTRICT, -- relacion recursiva: jefe directo del mismo hospital
    ADD CONSTRAINT chk_medico_no_autosupervisor CHECK (id_supervisor IS NULL OR id_supervisor <> id_medico), -- valida que un medico no sea su propio jefe
    ADD CONSTRAINT chk_medico_director_sin_supervisor CHECK (cargo <> 'Director Medico' OR id_supervisor IS NULL); -- valida que el director medico no reporte a nadie

-- Un solo director medico por hospital
CREATE UNIQUE INDEX uq_medico_un_director_por_hospital ON medico (id_hospital) WHERE cargo = 'Director Medico';
-- Acelera el recorrido de la jerarquia (consultas recursivas)
CREATE INDEX idx_medico_supervisor ON medico (id_supervisor);

-- ---------------------------------------------------------------------------------------------
-- 3. SUBTIPO ENFERMERO
-- ---------------------------------------------------------------------------------------------
ALTER TABLE enfermero
    ADD COLUMN id_personal       INTEGER,
    ADD COLUMN tipo_personal     VARCHAR(10) NOT NULL DEFAULT 'Enfermero'
        CONSTRAINT chk_enfermero_tipo_personal CHECK (tipo_personal = 'Enfermero'), -- valida que el subtipo solo enlace con personal de tipo Enfermero
    ADD COLUMN numero_colegiado  VARCHAR(20) UNIQUE
        CONSTRAINT chk_enfermero_colegiado CHECK (numero_colegiado IS NULL OR numero_colegiado ~ '^[A-Z0-9-]{3,20}$'); -- valida el formato del numero de colegiado

INSERT INTO personal (tipo_personal, nombre, dpi, fecha_contratacion)
SELECT 'Enfermero', nombre, dpi, DATE '2026-01-01' FROM enfermero ORDER BY id_enfermero;

UPDATE enfermero e SET id_personal = p.id_personal
FROM personal p WHERE p.tipo_personal = 'Enfermero' AND p.dpi = e.dpi;

ALTER TABLE enfermero
    ALTER COLUMN id_personal SET NOT NULL,
    ADD CONSTRAINT uq_enfermero_id_personal UNIQUE (id_personal),
    ADD CONSTRAINT fk_enfermero_personal FOREIGN KEY (id_personal, tipo_personal)
        REFERENCES personal (id_personal, tipo_personal) ON DELETE RESTRICT ON UPDATE CASCADE;

-- ---------------------------------------------------------------------------------------------
-- 4. SUBTIPO PERSONAL_ENCARGADO
-- ---------------------------------------------------------------------------------------------
ALTER TABLE personal_encargado
    ADD COLUMN id_personal    INTEGER,
    ADD COLUMN tipo_personal  VARCHAR(10) NOT NULL DEFAULT 'Encargado'
        CONSTRAINT chk_encargado_tipo_personal CHECK (tipo_personal = 'Encargado'); -- valida que el subtipo solo enlace con personal de tipo Encargado

INSERT INTO personal (tipo_personal, nombre, dpi, telefono, fecha_contratacion)
SELECT 'Encargado', nombre, dpi, telefono, DATE '2026-01-01' FROM personal_encargado ORDER BY id_encargado;

UPDATE personal_encargado e SET id_personal = p.id_personal
FROM personal p WHERE p.tipo_personal = 'Encargado' AND p.dpi = e.dpi;

ALTER TABLE personal_encargado
    ALTER COLUMN id_personal SET NOT NULL,
    ADD CONSTRAINT uq_encargado_id_personal UNIQUE (id_personal),
    ADD CONSTRAINT fk_encargado_personal FOREIGN KEY (id_personal, tipo_personal)
        REFERENCES personal (id_personal, tipo_personal) ON DELETE RESTRICT ON UPDATE CASCADE;

-- ---------------------------------------------------------------------------------------------
-- 5. Columnas del Proyecto 1 conservadas como espejo (migracion no destructiva)
--    La fuente de verdad ahora es PERSONAL; los triggers evitan que ambas copias diverjan.
-- ---------------------------------------------------------------------------------------------
COMMENT ON COLUMN medico.nombre IS 'Espejo de personal.nombre (columna del Proyecto 1 conservada; la mantiene un trigger)';
COMMENT ON COLUMN medico.dpi IS 'Espejo de personal.dpi (columna del Proyecto 1 conservada; la mantiene un trigger)';
COMMENT ON COLUMN medico.telefono IS 'Espejo de personal.telefono (columna del Proyecto 1 conservada; la mantiene un trigger)';
COMMENT ON COLUMN enfermero.nombre IS 'Espejo de personal.nombre (columna del Proyecto 1 conservada; la mantiene un trigger)';
COMMENT ON COLUMN enfermero.dpi IS 'Espejo de personal.dpi (columna del Proyecto 1 conservada; la mantiene un trigger)';
COMMENT ON COLUMN personal_encargado.nombre IS 'Espejo de personal.nombre (columna del Proyecto 1 conservada; la mantiene un trigger)';
COMMENT ON COLUMN personal_encargado.dpi IS 'Espejo de personal.dpi (columna del Proyecto 1 conservada; la mantiene un trigger)';
COMMENT ON COLUMN personal_encargado.telefono IS 'Espejo de personal.telefono (columna del Proyecto 1 conservada; la mantiene un trigger)';

-- Al insertar un subtipo, copia nombre/dpi/telefono desde PERSONAL (asi basta con indicar id_personal)
CREATE FUNCTION fn_subtipo_heredar_personal() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    p personal%ROWTYPE;
BEGIN
    SELECT * INTO p FROM personal WHERE id_personal = NEW.id_personal;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'No existe personal con id_personal = %: primero se inserta el supertipo', NEW.id_personal;
    END IF;
    NEW.nombre := p.nombre;
    NEW.dpi := p.dpi;
    IF TG_TABLE_NAME <> 'enfermero' THEN  -- enfermero no tenia columna telefono en el Proyecto 1
        NEW.telefono := p.telefono;
    END IF;
    RETURN NEW;
END
$$;
COMMENT ON FUNCTION fn_subtipo_heredar_personal() IS 'Copia al subtipo los datos comunes del supertipo al insertar (columnas espejo)';

CREATE TRIGGER trg_medico_heredar_personal BEFORE INSERT ON medico
    FOR EACH ROW EXECUTE FUNCTION fn_subtipo_heredar_personal();
CREATE TRIGGER trg_enfermero_heredar_personal BEFORE INSERT ON enfermero
    FOR EACH ROW EXECUTE FUNCTION fn_subtipo_heredar_personal();
CREATE TRIGGER trg_encargado_heredar_personal BEFORE INSERT ON personal_encargado
    FOR EACH ROW EXECUTE FUNCTION fn_subtipo_heredar_personal();

-- Al actualizar datos comunes en PERSONAL, propaga el cambio a las columnas espejo del subtipo
CREATE FUNCTION fn_personal_propagar_datos() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.tipo_personal = 'Medico' THEN
        UPDATE medico SET nombre = NEW.nombre, dpi = NEW.dpi, telefono = NEW.telefono WHERE id_personal = NEW.id_personal;
    ELSIF NEW.tipo_personal = 'Enfermero' THEN
        UPDATE enfermero SET nombre = NEW.nombre, dpi = NEW.dpi WHERE id_personal = NEW.id_personal;
    ELSE
        UPDATE personal_encargado SET nombre = NEW.nombre, dpi = NEW.dpi, telefono = NEW.telefono WHERE id_personal = NEW.id_personal;
    END IF;
    RETURN NULL;
END
$$;
COMMENT ON FUNCTION fn_personal_propagar_datos() IS 'Propaga a las columnas espejo del subtipo los cambios de nombre, dpi y telefono hechos en personal';

CREATE TRIGGER trg_personal_propagar_datos AFTER UPDATE OF nombre, dpi, telefono ON personal
    FOR EACH ROW
    WHEN (OLD.nombre IS DISTINCT FROM NEW.nombre OR OLD.dpi IS DISTINCT FROM NEW.dpi OR OLD.telefono IS DISTINCT FROM NEW.telefono)
    EXECUTE FUNCTION fn_personal_propagar_datos();

-- ---------------------------------------------------------------------------------------------
-- 6. Jerarquia sin ciclos: un medico no puede quedar, directa o indirectamente, bajo su propio subordinado
-- ---------------------------------------------------------------------------------------------
CREATE FUNCTION fn_medico_evitar_ciclo() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.id_supervisor IS NULL THEN
        RETURN NEW;
    END IF;
    -- sube por la cadena de mando desde el supervisor propuesto; si llega al propio medico, habria un ciclo
    IF EXISTS (
        WITH RECURSIVE cadena AS (
            SELECT id_medico, id_supervisor FROM medico WHERE id_medico = NEW.id_supervisor
            UNION
            SELECT m.id_medico, m.id_supervisor FROM medico m JOIN cadena c ON m.id_medico = c.id_supervisor
        )
        SELECT 1 FROM cadena WHERE id_medico = NEW.id_medico
    ) THEN
        RAISE EXCEPTION 'El supervisor % ya depende del medico %: se formaria un ciclo en la jerarquia', NEW.id_supervisor, NEW.id_medico;
    END IF;
    RETURN NEW;
END
$$;
COMMENT ON FUNCTION fn_medico_evitar_ciclo() IS 'Impide ciclos en la relacion recursiva medico.id_supervisor';

CREATE TRIGGER trg_medico_evitar_ciclo BEFORE INSERT OR UPDATE OF id_supervisor ON medico
    FOR EACH ROW EXECUTE FUNCTION fn_medico_evitar_ciclo();

