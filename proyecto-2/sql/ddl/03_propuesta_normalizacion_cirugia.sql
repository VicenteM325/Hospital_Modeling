-- ---------------------------------------------------------------------------------------------
-- 1. Propuesta en 3FN: cada hecho se guarda una sola vez
-- ---------------------------------------------------------------------------------------------
CREATE TABLE propuesta_cirugia.especialidad (
    id_especialidad  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL UNIQUE
);
COMMENT ON TABLE propuesta_cirugia.especialidad IS 'Catalogo de especialidades de los cirujanos (antes repetida en cada fila del reporte)';

CREATE TABLE propuesta_cirugia.cirujano (
    id_cirujano      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(150) NOT NULL UNIQUE,
    id_especialidad  INTEGER NOT NULL
        CONSTRAINT fk_prop_cirujano_especialidad REFERENCES propuesta_cirugia.especialidad(id_especialidad)
        ON DELETE RESTRICT ON UPDATE CASCADE
);
COMMENT ON TABLE propuesta_cirugia.cirujano IS 'Cirujano con su especialidad, registrado una sola vez';

CREATE TABLE propuesta_cirugia.paciente (
    id_paciente  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(150) NOT NULL UNIQUE
);
COMMENT ON TABLE propuesta_cirugia.paciente IS 'Paciente operado, identificado por una llave propia y no por su nombre repetido';

CREATE TABLE propuesta_cirugia.diagnostico (
    codigo       VARCHAR(10) PRIMARY KEY,
    descripcion  VARCHAR(200) NOT NULL
);
COMMENT ON TABLE propuesta_cirugia.diagnostico IS 'Catalogo de diagnosticos: el codigo determina la descripcion';

CREATE TABLE propuesta_cirugia.insumo (
    id_insumo  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(150) NOT NULL UNIQUE
);
COMMENT ON TABLE propuesta_cirugia.insumo IS 'Catalogo de insumos: un solo nombre por insumo (evita variantes escritas a mano)';

CREATE TABLE propuesta_cirugia.cirugia (
    id_cirugia          INTEGER PRIMARY KEY,
    id_cirujano         INTEGER NOT NULL
        CONSTRAINT fk_prop_cirugia_cirujano REFERENCES propuesta_cirugia.cirujano(id_cirujano)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    id_paciente         INTEGER NOT NULL
        CONSTRAINT fk_prop_cirugia_paciente REFERENCES propuesta_cirugia.paciente(id_paciente)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    codigo_diagnostico  VARCHAR(10) NOT NULL
        CONSTRAINT fk_prop_cirugia_diagnostico REFERENCES propuesta_cirugia.diagnostico(codigo)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    fecha               DATE NOT NULL
);
COMMENT ON TABLE propuesta_cirugia.cirugia IS 'Cada cirugia con sus llaves foraneas; ya no repite datos del cirujano, paciente ni diagnostico';

CREATE TABLE propuesta_cirugia.cirugia_insumo (
    id_cirugia  INTEGER NOT NULL
        CONSTRAINT fk_prop_cirugiainsumo_cirugia REFERENCES propuesta_cirugia.cirugia(id_cirugia)
        ON DELETE CASCADE ON UPDATE CASCADE,
    id_insumo   INTEGER NOT NULL
        CONSTRAINT fk_prop_cirugiainsumo_insumo REFERENCES propuesta_cirugia.insumo(id_insumo)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    cantidad    INTEGER NOT NULL
        CONSTRAINT chk_prop_cirugiainsumo_cantidad CHECK (cantidad > 0), -- valida que la cantidad usada sea positiva
    PRIMARY KEY (id_cirugia, id_insumo)
);
COMMENT ON TABLE propuesta_cirugia.cirugia_insumo IS 'Reemplaza los grupos repetidos insumo_1/insumo_2: una fila por insumo usado, sin limite de insumos';

-- ---------------------------------------------------------------------------------------------
-- 2. Migracion de los datos del reporte a las tablas normalizadas
-- ---------------------------------------------------------------------------------------------
INSERT INTO propuesta_cirugia.especialidad (nombre)
SELECT DISTINCT especialidad_cirujano FROM propuesta_cirugia.reporte_cirugia_original;

INSERT INTO propuesta_cirugia.cirujano (nombre, id_especialidad)
SELECT DISTINCT r.nombre_cirujano, e.id_especialidad
FROM propuesta_cirugia.reporte_cirugia_original r
JOIN propuesta_cirugia.especialidad e ON e.nombre = r.especialidad_cirujano;

INSERT INTO propuesta_cirugia.paciente (nombre)
SELECT DISTINCT nombre_paciente FROM propuesta_cirugia.reporte_cirugia_original;

INSERT INTO propuesta_cirugia.diagnostico (codigo, descripcion)
SELECT DISTINCT codigo_diagnostico, descripcion_diagnostico FROM propuesta_cirugia.reporte_cirugia_original;

INSERT INTO propuesta_cirugia.insumo (nombre)
SELECT nombre_insumo_1 FROM propuesta_cirugia.reporte_cirugia_original WHERE nombre_insumo_1 IS NOT NULL
UNION
SELECT nombre_insumo_2 FROM propuesta_cirugia.reporte_cirugia_original WHERE nombre_insumo_2 IS NOT NULL;

INSERT INTO propuesta_cirugia.cirugia (id_cirugia, id_cirujano, id_paciente, codigo_diagnostico, fecha)
SELECT r.id_cirugia, c.id_cirujano, p.id_paciente, r.codigo_diagnostico, r.fecha
FROM propuesta_cirugia.reporte_cirugia_original r
JOIN propuesta_cirugia.cirujano c ON c.nombre = r.nombre_cirujano
JOIN propuesta_cirugia.paciente p ON p.nombre = r.nombre_paciente;

INSERT INTO propuesta_cirugia.cirugia_insumo (id_cirugia, id_insumo, cantidad)
SELECT r.id_cirugia, i.id_insumo, r.cantidad_insumo_1
FROM propuesta_cirugia.reporte_cirugia_original r
JOIN propuesta_cirugia.insumo i ON i.nombre = r.nombre_insumo_1
UNION ALL
SELECT r.id_cirugia, i.id_insumo, r.cantidad_insumo_2
FROM propuesta_cirugia.reporte_cirugia_original r
JOIN propuesta_cirugia.insumo i ON i.nombre = r.nombre_insumo_2;

-- ---------------------------------------------------------------------------------------------
-- 3. Vista que arma de nuevo el reporte original (hasta 2 insumos, ordenados por id) a partir de las tablas
-- ---------------------------------------------------------------------------------------------
CREATE VIEW propuesta_cirugia.v_reporte_cirugia AS
SELECT c.id_cirugia,
       ci.nombre AS nombre_cirujano,
       e.nombre AS especialidad_cirujano,
       p.nombre AS nombre_paciente,
       c.codigo_diagnostico,
       d.descripcion AS descripcion_diagnostico,
       i1.nombre AS nombre_insumo_1, i1.cantidad AS cantidad_insumo_1,
       i2.nombre AS nombre_insumo_2, i2.cantidad AS cantidad_insumo_2,
       c.fecha
FROM propuesta_cirugia.cirugia c
JOIN propuesta_cirugia.cirujano ci ON ci.id_cirujano = c.id_cirujano
JOIN propuesta_cirugia.especialidad e ON e.id_especialidad = ci.id_especialidad
JOIN propuesta_cirugia.paciente p ON p.id_paciente = c.id_paciente
JOIN propuesta_cirugia.diagnostico d ON d.codigo = c.codigo_diagnostico
LEFT JOIN LATERAL (
    SELECT i.nombre, x.cantidad FROM propuesta_cirugia.cirugia_insumo x JOIN propuesta_cirugia.insumo i USING (id_insumo)
    WHERE x.id_cirugia = c.id_cirugia ORDER BY i.id_insumo LIMIT 1 OFFSET 0) i1 ON TRUE
LEFT JOIN LATERAL (
    SELECT i.nombre, x.cantidad FROM propuesta_cirugia.cirugia_insumo x JOIN propuesta_cirugia.insumo i USING (id_insumo)
    WHERE x.id_cirugia = c.id_cirugia ORDER BY i.id_insumo LIMIT 1 OFFSET 1) i2 ON TRUE;
COMMENT ON VIEW propuesta_cirugia.v_reporte_cirugia IS 'Reconstruye el formato del reporte original desde las tablas normalizadas';

