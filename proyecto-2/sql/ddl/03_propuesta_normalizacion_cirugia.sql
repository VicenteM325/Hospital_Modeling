-- Propuesta de normalizacion del Reporte_Cirugia (Bloque E, objetivo 19)
-- El area de informatica usa una unica tabla:
--   Reporte_Cirugia (Id_cirugia, Nombre_cirujano, Especialidad_cirujano, Nombre_paciente, Codigo_diagnostico,
--                    Descripcion_diagnostico, Nombre_insumo_1, Cantidad_insumo_1, Nombre_insumo_2, Cantidad_insumo_2, Fecha)
--   1FN: grupo repetido (insumo 1 y 2): solo caben 2 insumos y sobran NULL; buscar un insumo exige revisar ambas columnas.
--   3FN: dependencias transitivas  Id_cirugia -> Nombre_cirujano -> Especialidad_cirujano  y
--        Id_cirugia -> Codigo_diagnostico -> Descripcion_diagnostico: los datos del cirujano y del diagnostico se repiten.
--   Anomalias: de insercion (no se registra un cirujano, diagnostico o insumo sin una cirugia), de actualizacion
--   (cambiar la descripcion de un diagnostico obliga a corregir muchas filas) y de borrado (al borrar la unica cirugia
--   de un diagnostico se pierde su descripcion).
-- La propuesta vive en su propio esquema para no chocar con las tablas insumo y especialidad del modelo hospitalario.
-- Ejecutar como usr_admin_bd, despues de sql/dcl/02_permiso_crear_esquemas.sql.

SET ROLE rol_administrador;
BEGIN;

CREATE SCHEMA propuesta_cirugia;
COMMENT ON SCHEMA propuesta_cirugia IS 'Propuesta de normalizacion del Reporte_Cirugia (objetivo 19), separada del modelo hospitalario';

-- ---------------------------------------------------------------------------------------------
-- 0. El reporte actual, tal como lo genera informatica (con datos de ejemplo ficticios)
-- ---------------------------------------------------------------------------------------------
